// Branching Paths: the last of four original pattern maps, and the only
// one built the opposite way from every other authored map here -- LAND
// grows outward from a centre as a tapering fractal tree over open water,
// rather than water being cut into solid land. That is a deliberate
// construction choice, not a stylistic one: a carved-river version of this
// idea cannot hit a sane land share at all, since the interior would have
// to start almost entirely solid for river channels alone to ever cut it
// down into the 30-50% band every authored map here is tuned to. Same
// authored-map pipeline as World otherwise.
//
// Legend:
//   ~  ocean        .  plains        ^  highland
//   A  mountain
//
// Four limbs grow out from the centre in a cross, each recursively
// splitting and tapering into narrower peninsulas -- lots of choke
// points, no single open front. A mountain core runs the thick base of
// each of the four main limbs, tapering to highland further out along the
// thinner branches.

