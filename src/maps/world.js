// is that every row stays the same length.
//
// Legend:
//   ~  ocean        .  plains        ^  highland
//   A  mountain     /  river (carved as water, so it blocks land attacks
//                      and is crossed by boat, never walked across)
//
// Geography is stylised for play, not traced: continents are fattened and
// the emptiest stretches of ocean shrunk, landing near 40% land against the
// procedural generator's own 46% (TARGET_LAND_SHARE in src/map.js). Ice
// (Greenland, Antarctica) is authored as highland on purpose -- expensive
// to take, and spawns never seed there since findSpawnPoints only seeds on
// plains.

